// Builds the web export and turns it into a single self-contained HTML string
// the host phone can serve to browser guests.
//
// Expo's `web.output: "single"` still emits the JS as a separate file for the
// classic `AppEntry` setup, so this script reads it back and inlines it into
// the page before writing `src/network/guestPage.ts`.
//
// Run: npm run build:guest
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const distDir = join(root, 'dist');
const outFile = join(root, 'src', 'network', 'guestPage.native.ts');

execSync('npx expo export --platform web', { cwd: root, stdio: 'inherit' });

const readDist = (rel) => readFileSync(join(distDir, rel), 'utf8');

// Every file Expo emitted, as a path relative to dist.
const distFiles = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else distFiles.push(relative(distDir, full).split('\\').join('/'));
  }
};
walk(distDir);

let html = readDist('index.html');

// Inline every local <script src="..."> and <link rel="stylesheet" href="...">
// the page references. A remote URL (http/https) is left alone.
html = html.replace(/<script\s+src="([^"]+)"\s*defer>\s*<\/script>/g, (tag, src) => {
  if (/^https?:/.test(src)) return tag;
  const rel = src.replace(/^\//, '');
  const code = readDist(rel);
  return `<script>\n${code}\n</script>`;
});
html = html.replace(/<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/?>/g, (tag, href) => {
  if (/^https?:/.test(href)) return tag;
  const rel = href.replace(/^\//, '');
  const css = readDist(rel);
  return `<style>\n${css}\n</style>`;
});

// Mobile viewport: lock the page to the device width, disable pinch zoom,
// and fill the dynamic viewport so no dead space shows below the URL bar.
html = html.replace(
  /<meta\s+name="viewport"[^>]*\/?>/,
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover" />',
);
html = html.replace('</head>', `<style>
  html, body {
    height: 100% !important;
    margin: 0 !important;
    padding: 0 !important;
    overflow: hidden !important;
    position: fixed !important;
    width: 100% !important;
    inset: 0;
  }
  #root {
    height: 100dvh !important;
    max-height: 100dvh !important;
    overflow: hidden !important;
  }
  * { -webkit-tap-highlight-color: transparent !important; box-sizing: border-box; }
  input, textarea, select { font-size: 16px !important; }
</style></head>`);

// Inline binary assets (icon fonts, images) as base64 data URIs. Without this
// the browser asks the phone for `assets/…/*.ttf` and gets HTML back — the
// icon fonts never load and every button shows fallback glyphs.
const MIME = {
  '.ttf': 'font/ttf', '.woff': 'font/woff', '.woff2': 'font/woff2',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.gif': 'image/gif', '.svg': 'image/svg+xml', '.webp': 'image/webp',
};
  // The leading-slash form (`/assets/...`) must be replaced FIRST: replacing
  // the bare form first would strip `assets/...` out of `/assets/...` and
  // leave a stray `/` before the data URI, which the browser then treats as
  // a URL path instead of a data URI.
  for (const rel of distFiles) {
    if (rel === 'index.html' || rel === 'metadata.json') continue;
    const ext = rel.slice(rel.lastIndexOf('.')).toLowerCase();
    const mime = MIME[ext];
    if (!mime) continue;
    const dataUri = `data:${mime};base64,${readFileSync(join(distDir, rel)).toString('base64')}`;
    html = html.split('/' + rel).join(dataUri);
    html = html.split(rel).join(dataUri);
  }

writeFileSync(
  outFile,
  '// Generated by scripts/build-guest-page.mjs — do not edit by hand.\n'
    + '// Source: `npx expo export --platform web`, JS/CSS inlined by the script.\n'
    + `export const GUEST_PAGE_HTML = ${JSON.stringify(html)};\n`,
);

rmSync(distDir, { recursive: true, force: true });
console.log(`Wrote ${outFile} (${(html.length / 1024).toFixed(0)} KB, ${distFiles.length} source files inlined)`);
